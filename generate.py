def extract_json(text):
    text = text.strip()
    a, b = text.find("{"), text.rfind("}")
    if a == -1 or b == -1:
        raise ValueError("no JSON found")
    return json.loads(text[a:b + 1])


def ask_gemini(prompt):
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key:
        raise RuntimeError("no Gemini key")
    model = os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    body = {"contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"responseMimeType": "application/json", "temperature": 0.9}}
    r = requests.post(url, headers={"x-goog-api-key": key}, json=body, timeout=120)
    if r.status_code != 200:
        raise RuntimeError(f"Gemini HTTP {r.status_code}: {r.text[:200]}")
    return r.json()["candidates"][0]["content"]["parts"][0]["text"]


def ask_pollinations(prompt):
    body = {"model": "openai", "seed": random.randint(1, 10**6),
            "messages": [{"role": "system", "content": "Reply with valid JSON only."},
                         {"role": "user", "content": prompt}]}
    r = requests.post("https://text.pollinations.ai/openai", json=body, timeout=180)
    if r.status_code != 200:
        raise RuntimeError(f"Pollinations HTTP {r.status_code}: {r.text[:200]}")
    return r.json()["choices"][0]["message"]["content"]


def generate_story(theme, environment, recent):
    prompt = build_prompt(theme, environment, recent)
    providers = [("gemini", ask_gemini), ("pollinations", ask_pollinations)]
    last = None
    for attempt in range(3):
        for name, fn in providers:
            try:
                story = extract_json(fn(prompt))
                assert isinstance(story.get("scenes"), list) and len(story["scenes"]) >= 4
                for sc in story["scenes"]:
                    assert sc.get("narration")
                    if sc.get("mood") not in MOODS:
                        sc["mood"] = "mysterious"
                story.setdefault("title", "Untitled")
                story.setdefault("caption", "")
                story.setdefault("hashtags", [])
                words = sum(len(sc["narration"].split()) for sc in story["scenes"])
                print(f"story from {name} ({words} words)")
                return story
            except Exception as e:
                last = f"{name}: {e}"
                print("story retry ->", last)
        time.sleep(5 * (attempt + 1))
    raise RuntimeError(f"All text providers failed. Last: {last}")


# --------------------------------------------------------------------------- voice
def breathe(text):
    """Dramatic breathing pauses: sentence ends become ellipses."""
    return re.sub(r"\.\s+", "... ", text.strip())


def eleven_tts(text, voice_id, path):
    key = os.environ.get("ELEVENLABS_API_KEY", "").strip()
    if not key:
        return False
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}"
    body = {"text": breathe(text), "model_id": "eleven_multilingual_v2",
            "voice_settings": {"stability": 0.55, "similarity_boost": 0.8,
                               "style": 0.35, "use_speaker_boost": True}}
    r = requests.post(url, headers={"xi-api-key": key, "Accept": "audio/mpeg"},
                      params={"output_format": "mp3_44100_128"}, json=body, timeout=120)
    if r.status_code != 200 or len(r.content) < 1000:
        raise RuntimeError(f"ElevenLabs HTTP {r.status_code}: {r.text[:200]}")
    pathlib.Path(path).write_bytes(r.content)
    return True


async def _edge_tts(text, voice, path):
    import edge_tts
    await edge_tts.Communicate(breathe(text), voice, rate="-7%", pitch="-2Hz").save(str(path))


def make_voice(text, voice_idx, path):
    if SELFTEST:
        run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anoisesrc=d=3.5:c=pink:a=0.02",
             "-ar", "24000", "-ac", "1", str(path)])
        return
    voice_id = os.environ.get("ELEVENLABS_VOICE_ID", "").strip() or ELEVEN_VOICES[voice_idx % len(ELEVEN_VOICES)]
    try:
        if eleven_tts(text, voice_id, path):
            return
    except Exception as e:
        print("ElevenLabs failed, falling back to edge-tts:", e)
    for attempt in range(3):
        try:
            asyncio.run(_edge_tts(text, EDGE_VOICE, path))
            if pathlib.Path(path).stat().st_size > 1000:
                return
        except Exception as e:
            print("tts retry:", e)
        time.sleep(3)
    raise RuntimeError("TTS failed")



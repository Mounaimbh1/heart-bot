def fallback_cutout(img):
    """Used only if rembg is unavailable: GrabCut seeded with a head/shoulders prior."""
    arr = np.asarray(img.convert("RGB"))
    h, w = arr.shape[:2]
    try:
        import cv2
        mask = np.full((h, w), cv2.GC_PR_BGD, np.uint8)
        mask[int(h * 0.04):, int(w * 0.02):int(w * 0.98)] = cv2.GC_PR_FGD
        mask[:int(h * 0.04), :] = cv2.GC_BGD                                    # top border
        mask[:int(h * 0.55), :int(w * 0.04)] = cv2.GC_BGD                       # left/right margins above shoulders
        mask[:int(h * 0.55), int(w * 0.96):] = cv2.GC_BGD
        cv2.ellipse(mask, (w // 2, int(h * 0.40)), (int(w * 0.17), int(h * 0.24)), 0, 0, 360, cv2.GC_FGD, -1)  # head core
        mask[int(h * 0.90):, int(w * 0.05):int(w * 0.95)] = cv2.GC_FGD                 # jacket at the bottom
        bgd, fgd = np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64)
        cv2.grabCut(np.ascontiguousarray(arr[:, :, ::-1]), mask, None, bgd, fgd, 6, cv2.GC_INIT_WITH_MASK)
        alpha = np.where((mask == 1) | (mask == 3), 255, 0).astype(np.uint8)
    except Exception as e:
        print("grabcut unavailable, using luminance mask:", e)
        lum = arr.astype(np.float32).mean(axis=2)
        corners = np.concatenate([lum[:40, :40].ravel(), lum[:40, -40:].ravel()])
        alpha = (np.abs(lum - float(np.median(corners))) > 22).astype(np.uint8) * 255
    out = img.convert("RGBA")
    out.putalpha(Image.fromarray(alpha, "L"))
    return out


def alpha_ok(rgba):
    a = np.asarray(rgba.split()[3], dtype=np.float32) / 255.0
    coverage = float((a > 0.5).mean())
    return 0.12 < coverage < 0.92


def refine_alpha(rgba):
    a = rgba.split()[3]
    a = a.filter(ImageFilter.MinFilter(3))               # eat the dark fringe
    a = a.filter(ImageFilter.GaussianBlur(1.1))          # soft natural edge
    arr = np.asarray(a, dtype=np.float32) / 255.0
    arr = np.clip((arr - 0.06) / 0.88, 0, 1)
    arr = arr * arr * (3 - 2 * arr)                      # smoothstep
    out = rgba.copy()
    out.putalpha(Image.fromarray((arr * 255).astype(np.uint8), "L"))
    return out


def make_cutout(img):
    cut = None
    if not SELFTEST:
        try:
            from rembg import new_session, remove
            session = new_session(os.environ.get("REMBG_MODEL", "isnet-general-use"))
            cut = remove(img, session=session).convert("RGBA")
            if not alpha_ok(cut):
                print("rembg mask looks wrong, using fallback")
                cut = None
        except Exception as e:
            print("rembg failed, using fallback:", e)
    if cut is None:
        cut = fallback_cutout(img)
        if not alpha_ok(cut):
            raise RuntimeError("Could not isolate the character from the background")
    return refine_alpha(cut)


def bust_crop(cut):
    """Crop to head + shoulders and fade the bottom so no flat cut edge is visible."""
    w, h = cut.size
    cut = cut.crop((0, 0, w, int(h * 0.78)))
    a = np.asarray(cut.split()[3], dtype=np.float32) / 255.0
    rows = np.where(a.max(axis=1) > 0.05)[0]
    top = int(rows[0]) if len(rows) else 0
    cut = cut.crop((0, top, cut.width, cut.height))
    a = a[top:]
    ch = a.shape[0]
    fade = max(2, int(ch * 0.18))
    ramp = np.ones(ch, dtype=np.float32)
    ramp[-fade:] = np.linspace(1, 0, fade) ** 1.3
    out = cut.copy()
    out.putalpha(Image.fromarray((a * ramp[:, None] * 255).astype(np.uint8), "L"))
    return out



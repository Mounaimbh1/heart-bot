def render_scene(work, i, voice_dur, clip_len):
    frames = max(2, int(clip_len * FPS))
    if i % 2 == 0:
        x_bg = f"(iw-iw/zoom)*(on/{frames})+3*sin(on/11)"
    else:
        x_bg = f"(iw-iw/zoom)*(1-on/{frames})+3*sin(on/11)"
    z_bg = f"1.0+0.08*on/{frames}"
    y_bg = "ih/2-(ih/zoom/2)+2*sin(on/7)"
    fg_zoom = f"(1+0.045*t/{clip_len:.3f})"
    fc = (
        f"[0:v]zoompan=z='{z_bg}':x='{x_bg}':y='{y_bg}':d={frames}:s={W}x{H}:fps={FPS},format=yuv420p[bg];"
        f"[1:v]format=rgba,scale=w='trunc(iw*{fg_zoom}/2)*2':h='trunc(ih*{fg_zoom}/2)*2':eval=frame[fg];"
        "[bg][fg]overlay=x='(W-w)/2+5*sin(2.1*t)+2.5*sin(5.3*t+1)':"
        "y='(H-h)/2+4*sin(1.7*t+2)+2*sin(4.4*t)':format=auto:eval=frame,"
        f"eq=contrast=1.04:saturation=1.05,subtitles=s{i}.ass,format=yuv420p[v]"
    )
    run(["ffmpeg", "-y", "-i", f"bg{i}.jpg", "-loop", "1", "-framerate", str(FPS), "-t", f"{clip_len:.3f}",
         "-i", f"fg{i}.png", "-filter_complex", fc, "-map", "[v]", "-an", "-t", f"{clip_len:.3f}",
         "-r", str(FPS), "-c:v", "libx264", "-preset", "fast", "-crf", "19", "-pix_fmt", "yuv420p",
         f"clip{i}.mp4"], cwd=work)


def join_clips(work, n, ds, total_len):
    inputs = []
    for i in range(n):
        inputs += ["-i", f"clip{i}.mp4"]
    tail = (f"fade=t=in:st=0:d=0.3,fade=t=out:st={max(0.0, total_len - 0.7):.2f}:d=0.7,format=yuv420p[v]")
    if n == 1:
        fc = f"[0:v]{tail}"
    else:
        parts, prev, start = [], "[0:v]", 0.0
        for i in range(1, n):
            start += ds[i - 1]
            out = f"[x{i}]"
            parts.append(f"{prev}[{i}:v]xfade=transition=fade:duration={XF}:offset={start:.3f}{out}")
            prev = out
        parts.append(f"{prev}{tail}")
        fc = ";".join(parts)
    run(["ffmpeg", "-y"] + inputs + ["-filter_complex", fc, "-map", "[v]", "-an", "-r", str(FPS),
                                     "-c:v", "libx264", "-preset", "fast", "-crf", "21",
                                     "-pix_fmt", "yuv420p", "joined.mp4"], cwd=work)


def make_video(idx, story, env, cutout, light_dir, out_path):
    work = OUT / f"work{idx}"
    work.mkdir(parents=True, exist_ok=True)
    seed_base = random.randint(1, 10**6)
    scenes = story["scenes"]
    n = len(scenes)
    voice_durs, ds, moods = [], [], []
    for i, sc in enumerate(scenes):
        make_voice(sc["narration"], idx, work / f"voice{i}.mp3")
        vd = media_duration(work / f"voice{i}.mp3")
        voice_durs.append(vd)
        ds.append(vd + 0.45)
        moods.append(sc["mood"])
        raw = fetch_background(env, ANGLES[i % len(ANGLES)], seed_base + i)
        bg = finish_background(raw, sc["mood"])
        bg.save(work / f"bg{i}.jpg", quality=93)
        fg = build_foreground(cutout, raw, POSES[i % len(POSES)], light_dir)
        fg.save(work / f"fg{i}.png")
        make_ass(sc["narration"], vd, work / f"s{i}.ass", offset=0.25)
        render_scene(work, i, vd, ds[i] + XF)
        time.sleep(1 if SELFTEST else 2)

    total_len = sum(ds) + XF
    starts = []
    acc = 0.0
    for i in range(n):
        starts.append(acc + 0.25)
        acc += ds[i]
    join_clips(work, n, ds, total_len)
    build_narration(work, n, starts, total_len, work / "narration.wav")
    music_durs = ds[:-1] + [ds[-1] + XF]
    make_music(moods, music_durs, work / "music.wav")
    fc = ("[2:a]lowpass=f=900,volume=0.12[m];"
          "[1:a][m]amix=inputs=2:duration=first:dropout_transition=0:normalize=0,"
          f"loudnorm=I=-15:TP=-1.5:LRA=9,afade=t=out:st={max(0.0, total_len - 1.2):.2f}:d=1.2[a]")
    run(["ffmpeg", "-y", "-i", "joined.mp4", "-i", "narration.wav", "-i", "music.wav",
         "-filter_complex", fc, "-map", "0:v", "-map", "[a]", "-c:v", "copy",
         "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", str(out_path)], cwd=work)
    if pathlib.Path(out_path).stat().st_size > 49 * 1024 * 1024:
        small = work / "small.mp4"
        run(["ffmpeg", "-y", "-i", str(out_path), "-c:v", "libx264", "-preset", "fast", "-crf", "28",
             "-c:a", "copy", "-movflags", "+faststart", str(small)])
        small.replace(out_path)
    return total_len


# --------------------------------------------------------------------------- telegram
def tg(method, **kw):
    url = f"https://api.telegram.org/bot{os.environ['TELEGRAM_BOT_TOKEN']}/{method}"
    return requests.post(url, timeout=300, **kw)


def send_video(path, caption):
    with open(path, "rb") as f:
        r = tg("sendVideo", data={"chat_id": os.environ["TELEGRAM_CHAT_ID"], "caption": caption[:1000],
                                  "supports_streaming": "true", "width": W, "height": H}, files={"video": f})
    if r.status_code != 200:
        raise RuntimeError(f"Telegram error: {r.text[:300]}")


def send_text(text):
    r = tg("sendMessage", data={"chat_id": os.environ["TELEGRAM_CHAT_ID"], "text": text[:4000]})
    if r.status_code != 200:
        print(f"Telegram text error: {r.text[:300]}")



# --------------------------------------------------------------------------- backgrounds
def is_valid_background(img):
    g = np.asarray(img.convert("L").resize((270, 480)), dtype=np.float32)
    if float(g.mean()) < 35.0 or float(g.std()) < 14.0:
        return False
    h, w = g.shape
    quads = [g[:h // 2, :w // 2], g[:h // 2, w // 2:], g[h // 2:, :w // 2], g[h // 2:, w // 2:]]
    return min(float(q.mean()) for q in quads) > 18.0


def procedural_background(palette, seed):
    """Guaranteed, bright, person-free fallback: gradient + soft bokeh + grain."""
    rng = np.random.default_rng(seed)
    w, h = 540, 960
    top, bot, glow = [np.array(c, np.float32) for c in palette]
    y = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    base = np.broadcast_to(top * (1 - y) + bot * y, (h, w, 3)).copy()
    img = Image.fromarray(np.clip(base, 0, 255).astype(np.uint8)).convert("RGBA")
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    for _ in range(28):
        x, yy, r = int(rng.integers(0, w)), int(rng.integers(0, h)), int(rng.integers(18, 70))
        col = tuple(int(v) for v in np.clip(glow * rng.uniform(0.7, 1.2), 0, 255)) + (int(rng.integers(35, 100)),)
        d.ellipse((x - r, yy - r, x + r, yy + r), fill=col)
    layer = layer.filter(ImageFilter.GaussianBlur(6))
    img = Image.alpha_composite(img, layer).convert("RGB")
    arr = np.asarray(img, dtype=np.float32) + rng.normal(0, 3.0, (h, w, 1))
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def fetch_background(env, angle, seed):
    if SELFTEST:
        return procedural_background(env["palette"], seed)
    prompt = (f"{env['prompt']}, empty scene, no people, no person, no humans, no text, "
              f"cinematic photograph, {angle}, vertical composition, shallow depth of field, "
              f"soft natural light, photorealistic, 8k")[:380]
    for attempt in range(5):
        model = "flux" if attempt < 3 else "turbo"
        url = (f"https://image.pollinations.ai/prompt/{quote(prompt, safe='')}"
               f"?width=768&height=1344&nologo=true&seed={seed + attempt * 17}&model={model}")
        try:
            r = requests.get(url, timeout=90)
            if r.status_code == 200 and r.headers.get("content-type", "").startswith("image"):
                tmp = OUT / f"_bg_{seed}.raw"
                tmp.write_bytes(r.content)
                try:
                    img = Image.open(tmp).convert("RGB")
                finally:
                    tmp.unlink(missing_ok=True)
                if is_valid_background(img):
                    return img
                print(f"background {attempt + 1} rejected (too dark / flat)")
        except Exception as e:
            print(f"background retry {attempt + 1}:", e)
        time.sleep(3)
    print("using procedural background fallback")
    return procedural_background(env["palette"], seed)


def finish_background(img, mood):
    bg = cover_resize(img.convert("RGB"), BW, BH)
    bg = ImageEnhance.Contrast(bg).enhance(1.05)
    bg = ImageEnhance.Color(bg).enhance(1.06)
    bg = Image.blend(bg, Image.new("RGB", (BW, BH), MOOD_COLORS.get(mood, (50, 45, 65))), 0.07)
    arr = np.asarray(bg, dtype=np.float32)
    yy = np.linspace(0, 1, BH, dtype=np.float32)[:, None]
    xx = np.linspace(-1, 1, BW, dtype=np.float32)[None, :]
    bottom = 1 - 0.55 * np.clip((yy - 0.55) / 0.45, 0, 1) ** 1.3      # darker lower third for subtitles
    vig = 1 - 0.22 * np.clip(xx ** 2 + (yy * 2 - 1) ** 2 - 0.35, 0, 1)
    arr = arr * (bottom * vig)[:, :, None]
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


# --------------------------------------------------------------------------- compositing
def build_foreground(cut, bg_img, pose, light_dir):
    """Colour-match, rim-light and place the real character on a transparent 1080x1920 layer."""
    cw, ch = cut.size
    tw = pose["w"]
    th = int(ch * tw / cw)
    c = cut.resize((tw, th), Image.Resampling.LANCZOS)
    rgb = np.asarray(c.convert("RGB"), dtype=np.float32) / 255.0
    a = np.asarray(c.split()[3], dtype=np.float32) / 255.0

    bg = np.asarray(bg_img.resize((270, 480)), dtype=np.float32).reshape(-1, 3) / 255.0
    mu_b, sd_b = bg.mean(0), bg.std(0) + 1e-3
    solid = a > 0.5
    if int(solid.sum()) > 100:
        px = rgb[solid]
        mu_c, sd_c = px.mean(0), px.std(0) + 1e-3
        gain = np.clip(sd_b / sd_c, 0.88, 1.12)
        matched = (rgb - mu_c) * gain + mu_c + (mu_b - mu_c) * 0.15
        rgb = rgb * 0.55 + matched * 0.45

    # light wrap: edges pick up a little of the environment colour
    wrap = np.clip(a * (1 - blur_f(a, 6)) * 2.0, 0, 1)
    rgb = rgb * (1 - wrap[..., None] * 0.22) + mu_b * (wrap[..., None] * 0.22)

    # subtle rim light on the side facing the scene's main light
    d = 12
    rim_side = a * (1 - np.roll(a, -d * light_dir, axis=1))
    rim_top = a * (1 - np.roll(a, 8, axis=0)) * 0.5
    rim = blur_f(np.clip(rim_side + rim_top, 0, 1), 4)
    lum = bg.mean(1)
    bright = bg[lum >= np.quantile(lum, 0.85)].mean(0)
    rim_col = np.clip(bright / (bright.max() + 1e-3) * 1.1, 0, 1)
    rgb = 1 - (1 - rgb) * (1 - rim[..., None] * rim_col * 0.6)
    rgb = np.clip(rgb, 0, 1)

    x = int((W - tw) / 2 + pose["dx"])
    y = int(pose["top"])
    char_rgba = Image.fromarray(np.dstack([(rgb * 255).astype(np.uint8), (a * 255).astype(np.uint8)]), "RGBA")
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    layer.paste(char_rgba, (x, y), char_rgba)

    # soft cast shadow on the scene behind the character
    alpha_full = Image.new("L", (W, H), 0)
    alpha_full.paste(char_rgba.split()[3], (x, y))
    shadow = alpha_full.filter(ImageFilter.GaussianBlur(38))
    shadow = ImageChops.offset(shadow, -22 * light_dir, 26).point(lambda v: int(v * 0.5))
    shadow_rgba = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    shadow_rgba.putalpha(shadow)
    return Image.alpha_composite(shadow_rgba, layer)


# --------------------------------------------------------------------------- music
def make_music(moods, durs, path, sr=44100):
    xf = 1.0
    total = sum(durs)
    buf = np.zeros(int(sr * (total + 2 * xf)))
    pos = 0.0
    for mood, d in zip(moods, durs):
        t = np.arange(int(sr * (d + xf))) / sr
        sig = np.zeros_like(t)
        for i, f in enumerate(CHORDS.get(mood, CHORDS["mysterious"])):
            for det in (-0.35, 0.0, 0.35):
                sig += np.sin(2 * np.pi * (f + det) * t + i) / (1 + 0.4 * i)
        sig /= (np.max(np.abs(sig)) + 1e-9)
        ramp = np.linspace(0, 1, int(sr * xf))
        env = np.ones(len(sig))
        env[:len(ramp)] = ramp
        env[-len(ramp):] = ramp[::-1]
        start = int(sr * max(0.0, pos - xf / 2))
        end = min(start + len(sig), len(buf))
        buf[start:end] += (sig * env)[:end - start]
        pos += d
    buf = buf[:int(sr * total)]
    buf = buf / (np.max(np.abs(buf)) + 1e-9) * 0.55
    fade = int(sr * 1.5)
    buf[:fade] *= np.linspace(0, 1, fade)
    buf[-fade:] *= np.linspace(1, 0, fade)
    stereo = np.stack([buf, np.roll(buf, 260)], axis=1)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes((stereo * 32767).astype(np.int16).tobytes())


def build_narration(work, n, starts, total, path, sr=44100):
    buf = np.zeros(int(sr * (total + 0.5)), dtype=np.float32)
    for i in range(n):
        wav = work / f"v{i}.wav"
        run(["ffmpeg", "-y", "-i", str(work / f"voice{i}.mp3"), "-ar", str(sr), "-ac", "1", "-f", "wav", str(wav)])
        with wave.open(str(wav), "rb") as w:
            raw = w.readframes(w.getnframes())
        arr = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768.0
        s = int(starts[i] * sr)
        e = min(s + len(arr), len(buf))
        if e > s:
            buf[s:e] += arr[:e - s]
    peak = float(np.max(np.abs(buf)))
    if peak > 0.95:
        buf *= 0.95 / peak
    stereo = np.stack([buf, buf], axis=1)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes((stereo * 32767).astype(np.int16).tobytes())


# --------------------------------------------------------------------------- subtitles
def ass_time(s):
    return f"{int(s // 3600)}:{int(s % 3600 // 60):02d}:{s % 60:05.2f}"


def make_ass(text, voice_dur, path, offset=0.25):
    words = text.replace("{", "").replace("}", "").split()
    chunks, cur = [], []
    for w in words:
        cur.append(w)
        if len(cur) >= 4 or len(" ".join(cur)) >= 22 or (w[-1] in ".!?," and len(cur) >= 2):
            chunks.append(" ".join(cur))
            cur = []
    if cur:
        chunks.append(" ".join(cur))
    weight = sum(len(c) for c in chunks) or 1
    usable = max(1.0, voice_dur * 0.97)
    tag = "{\\an5\\pos(540,%d)\\fscx88\\fscy88\\t(0,140,\\fscx100\\fscy100)}" % SUB_Y
    t = offset
    lines = []
    for c in chunks:
        d = usable * len(c) / weight
        lines.append(f"Dialogue: 0,{ass_time(t)},{ass_time(t + d)},Main,,0,0,0,,{tag}{c}")
        t += d
    header = (
        "[Script Info]\nScriptType: v4.00+\nPlayResX: 1080\nPlayResY: 1920\nWrapStyle: 0\n\n"
        "[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, "
        "Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        "Style: Main,DejaVu Sans,76,&H00FFFFFF,&H000000FF,&H00000000,&HA0000000,-1,0,0,0,100,100,1,0,1,7,3,5,70,70,0,1\n\n"
        "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )
    pathlib.Path(path).write_text(header + "\n".join(lines) + "\n", encoding="utf-8")


